def semantic_icon(widget: QWidget, role: IconRole) -> QIcon:
    """Render a 24 px Lucide icon using the widget's foreground color."""

    color = widget.palette().buttonText().color().name()
    svg = (
        '<svg width="24" height="24" viewBox="0 0 24 24" fill="none" '
        f'stroke="{color}" stroke-width="2" stroke-linecap="round" '
        f'stroke-linejoin="round" xmlns="http://www.w3.org/2000/svg">'
        f"{_LUCIDE_BODY[role]}</svg>"
    )
    pixmap = QPixmap()
    if not pixmap.loadFromData(QByteArray(svg.encode()), "SVG"):
        return QIcon()
    return QIcon(pixmap)
